#!/usr/bin/env python3
"""Generate build/gen/nv_tables.h: fixed-point lookup tables and vector geometry for NOICE VOICE."""
import json
import math
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CHIMERA_JSON = REPO_ROOT / "assets" / "noice" / "chimera_geometry.json"
JHF_FILE = REPO_ROOT / "assets" / "noice" / "hershey_simplex.jhf"
OUT_HEADER = REPO_ROOT / "build" / "gen" / "nv_tables.h"

# Screen transformation parameters:
# SX = int(round(OX + scale * x))
# SY = int(round(OY - scale * y))
SCALE = 13.5
OX = 45.0   # Center head nicely in the 0..170 horizontal span
OY = 160.0  # Glottis rests near y=160, skull top near y=20

def tx(x):
    return int(round(OX + SCALE * x))

def ty(y):
    return int(round(OY - SCALE * y))

def cm2_to_q12(area_cm2):
    # Q12: 1.0 cm^2 = 4096
    val = int(round(area_cm2 * 4096.0))
    return max(41, min(65535, val))  # 41 = 0.01 cm^2 floor

def parse_jhf(filename):
    glyphs = []
    with open(filename, 'r') as f:
        for idx, line in enumerate(f):
            if len(line) < 10:
                continue
            gid = int(line[0:5].strip())
            npairs = int(line[5:8].strip())
            lm = ord(line[8]) - ord('R')
            rm = ord(line[9]) - ord('R')
            width = rm - lm
            
            raw_coords = line[10:].rstrip('\r\n')
            strokes = []
            curr_stroke = []
            i = 0
            while i < len(raw_coords) - 1:
                p1 = raw_coords[i]
                p2 = raw_coords[i+1]
                i += 2
                if p1 == ' ' and p2 == 'R':
                    if curr_stroke:
                        strokes.append(curr_stroke)
                        curr_stroke = []
                else:
                    x = ord(p1) - ord('R') - lm
                    y = ord(p2) - ord('R')
                    curr_stroke.append((x, y))
            if curr_stroke:
                strokes.append(curr_stroke)
            
            ascii_code = 32 + idx
            char = chr(ascii_code) if 32 <= ascii_code <= 126 else '?'
            glyphs.append({
                'ascii': ascii_code,
                'char': char,
                'width': width,
                'strokes': strokes
            })
    return glyphs

def main():
    print(f"Loading {CHIMERA_JSON}...")
    with open(CHIMERA_JSON) as f:
        chimera = json.load(f)

    glyphs = parse_jhf(JHF_FILE)
    print(f"Loaded {len(glyphs)} Hershey glyphs.")

    bodies = chimera['bodies']
    male = bodies['male']
    grid_3x3 = chimera['grid_3x3']
    onsets = chimera['onset_list']
    codas = chimera['coda_list']

    lines = []
    lines.append("/* SPDX-License-Identifier: GPL-3.0-only */")
    lines.append("/* Auto-generated by tools/noice/gen_tables.py - DO NOT EDIT */")
    lines.append("#ifndef NV_TABLES_H")
    lines.append("#define NV_TABLES_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("/* 2D point on 240x240 screen */")
    lines.append("typedef struct { int16_t x, y; } nv_pt_t;")
    lines.append("")
    lines.append("/* Ray rung for pressure visualization */")
    lines.append("typedef struct { nv_pt_t inner, outer; } nv_ray_t;")
    lines.append("")
    lines.append("/* Consonant definition */")
    lines.append("typedef struct {")
    lines.append("    const char *ipa;")
    lines.append("    uint8_t manner;      /* 0:stop, 1:nasal, 2:fricative, 3:approximant, 4:glottal */")
    lines.append("    uint8_t voiced;")
    lines.append("    uint8_t dur_ms;")
    lines.append("    uint8_t nasal;")
    lines.append("    uint8_t constr_sec;  /* 0..21 section of constriction */")
    lines.append("    uint16_t min_area;   /* Q12 cm^2 */")
    lines.append("    uint16_t areas[22];  /* Q12 cm^2 */")
    lines.append("} nv_consonant_t;")
    lines.append("")

    # 1. 3x3 Vowel Grid Area Functions for each body (Male, Female, Child)
    # Dimensions: [body 0..2][row 0..2][col 0..2][22 sections]
    lines.append("/* 3x3 Vowel Grid Area Functions (22 sections @ Q12 cm^2: 8 pharynx, 14 oral) */")
    lines.append("/* Bodies: 0 = Male, 1 = Female, 2 = Child */")
    lines.append("/* Grid rows (Jaw): 0 = close, 1 = mid, 2 = open */")
    lines.append("/* Grid cols (Tongue): 0 = front, 1 = central, 2 = back */")
    lines.append("static const uint16_t NV_VOWEL_GRID[3][3][3][22] = {")
    for b_idx, b_name in enumerate(["male", "female", "child"]):
        b_data = bodies[b_name]
        lines.append(f"    /* Body {b_idx}: {b_name} */")
        lines.append("    {")
        for r in range(3):
            lines.append(f"        /* Row {r} */")
            lines.append("        {")
            for c in range(3):
                v_name = grid_3x3[r][c]
                v_data = b_data['vowels'][v_name]
                areas = [cm2_to_q12(a) for a in v_data['areas_22']]
                areas_str = ", ".join(f"{a}" for a in areas)
                lines.append(f"            /* ({r},{c}) /{v_name}/ */ {{ {areas_str} }},")
            lines.append("        },")
        lines.append("    },")
    lines.append("};")
    lines.append("")

    # 2. All 22 Calibrated Vowels List
    # We export the list of vowel names and male areas for the VOWEL KEYS on SCL
    vowel_keys = sorted(list(male['vowels'].keys()))
    lines.append(f"#define NV_NVOWELS {len(vowel_keys)}")
    lines.append("static const char *const NV_VOWEL_NAMES[NV_NVOWELS] = {")
    for v in vowel_keys:
        lines.append(f'    "{v}",')
    lines.append("};")
    lines.append("static const uint16_t NV_VOWEL_AREAS[NV_NVOWELS][22] = {")
    for v in vowel_keys:
        areas = [cm2_to_q12(a) for a in male['vowels'][v]['areas_22']]
        areas_str = ", ".join(f"{a}" for a in areas)
        lines.append(f"    /* /{v}/ */ {{ {areas_str} }},")
    lines.append("};")
    lines.append("")

    # 3. Consonants (Onsets and Codas)
    manner_map = {"stop": 0, "nasal": 1, "fricative": 2, "affricate": 2, "approximant": 3, "lateral": 3, "glottal": 4, "tap": 0, "trill": 3}
    lines.append(f"#define NV_NONSETS {len(onsets)}")
    lines.append(f"static const nv_consonant_t NV_ONSETS[{len(onsets)}] = {{")
    for c in onsets:
        c_data = male['consonants'].get(c)
        if not c_data:
            # Fallback
            c_data = {"name": c, "manner": "fricative", "voicing": "voiceless", "dur": 0.08, "nasal": False, "constriction_idx": 18, "min_area": 0.1, "target_areas_22": [1.0]*22}
        manner = manner_map.get(c_data['manner'], 2)
        voiced = 1 if c_data['voicing'] == "voiced" else 0
        dur_ms = int(round(c_data['dur'] * 1000.0))
        nasal = 1 if c_data['nasal'] else 0
        constr = c_data['constriction_idx']
        min_a = cm2_to_q12(c_data['min_area'])
        areas = [cm2_to_q12(a) for a in c_data['target_areas_22']]
        areas_str = ", ".join(f"{a}" for a in areas)
        lines.append(f'    {{ "{c}", {manner}, {voiced}, {dur_ms}, {nasal}, {constr}, {min_a}, {{ {areas_str} }} }},')
    lines.append("};")
    lines.append("")

    lines.append(f"#define NV_NCODAS {len(codas)}")
    lines.append(f"static const nv_consonant_t NV_CODAS[{len(codas)}] = {{")
    for c in codas:
        c_data = male['consonants'].get(c)
        if not c_data:
            # Fallback for vowel codas (like 'i', 'u', 'ə')
            v_data = male['vowels'].get(c)
            if v_data:
                areas = [cm2_to_q12(a) for a in v_data['areas_22']]
                areas_str = ", ".join(f"{a}" for a in areas)
                lines.append(f'    {{ "{c}", 3, 1, 60, 0, 14, 2048, {{ {areas_str} }} }},')
                continue
            c_data = {"name": c, "manner": "nasal", "voicing": "voiced", "dur": 0.08, "nasal": True, "constriction_idx": 18, "min_area": 0.1, "target_areas_22": [1.0]*22}
        manner = manner_map.get(c_data['manner'], 2)
        voiced = 1 if c_data['voicing'] == "voiced" else 0
        dur_ms = int(round(c_data['dur'] * 1000.0))
        nasal = 1 if c_data['nasal'] else 0
        constr = c_data['constriction_idx']
        min_a = cm2_to_q12(c_data['min_area'])
        areas = [cm2_to_q12(a) for a in c_data['target_areas_22']]
        areas_str = ", ".join(f"{a}" for a in areas)
        lines.append(f'    {{ "{c}", {manner}, {voiced}, {dur_ms}, {nasal}, {constr}, {min_a}, {{ {areas_str} }} }},')
    lines.append("};")
    lines.append("")

    # 4. Static Vector Head Outlines: Skull & Palate
    # male['skull_outer'] was snapshotted from schwa's dynamic f.outer polyline:
    #   [0..19]  = posterior pharyngeal wall (glottis -> y=45)
    #   [20..29] = frozen shut-velum oral roof (omit so opening the velum stays unobstructed)
    #   [30..63] = palate duplicate (drawn separately via NV_PALATE)
    #   [64..70] = frozen upper_lip_in (drawn dynamically via NV_UPPER_LIP)
    # Keep [0..19] and continue up along the nasopharynx vault to NV_VELUM[0] (56, 22).
    phar_wall_pts = [(tx(p['x']), ty(p['y'])) for p in male['skull_outer'][:20]]
    nasopharynx_pts = [(27, 39), (28, 33), (31, 27), (36, 23), (44, 21), (56, 22)]
    skull_pts = phar_wall_pts + nasopharynx_pts
    palate_pts = [(tx(p['x']), ty(p['y'])) for p in male['palate']]
    lines.append(f"#define NV_NSKULL {len(skull_pts)}")
    lines.append(f"static const nv_pt_t NV_SKULL[{len(skull_pts)}] = {{")
    for x, y in skull_pts:
        lines.append(f"    {{ {x}, {y} }},")
    lines.append("};")
    lines.append("")
    lines.append(f"#define NV_NPALATE {len(palate_pts)}")
    lines.append(f"static const nv_pt_t NV_PALATE[{len(palate_pts)}] = {{")
    for x, y in palate_pts:
        lines.append(f"    {{ {x}, {y} }},")
    lines.append("};")
    lines.append("")

    # 5. Dynamic Articulators for 3x3 grid: Tongue, Jaw, Lips, Velum, Rays
    # Tongue: [3][3][N_PTS]
    # Check max points across grid
    t_lens = [len(male['vowels'][grid_3x3[r][c]]['tongue']) for r in range(3) for c in range(3)]
    min_t_len = min(t_lens)
    print(f"Tongue points range: {min(t_lens)}..{max(t_lens)}, using {min_t_len}")
    lines.append(f"#define NV_NTONGUE {min_t_len}")
    lines.append(f"static const nv_pt_t NV_TONGUE[3][3][NV_NTONGUE] = {{")
    for r in range(3):
        lines.append("    {")
        for c in range(3):
            v_name = grid_3x3[r][c]
            pts = male['vowels'][v_name]['tongue'][:min_t_len]
            s_pts = ", ".join(f"{{ {tx(p['x'])}, {ty(p['y'])} }}" for p in pts)
            lines.append(f"        /* ({r},{c}) */ {{ {s_pts} }},")
        lines.append("    },")
    lines.append("};")
    lines.append("")

    # Jaw bone across 3 jaw heights (row 0, 1, 2)
    jaw_pts_0 = male['vowels'][grid_3x3[0][1]]['jaw_bone']
    jaw_pts_1 = male['vowels'][grid_3x3[1][1]]['jaw_bone']
    jaw_pts_2 = male['vowels'][grid_3x3[2][1]]['jaw_bone']
    n_jaw = len(jaw_pts_0)
    lines.append(f"#define NV_NJAW {n_jaw}")
    lines.append(f"static const nv_pt_t NV_JAW[3][NV_NJAW] = {{")
    for j_pts in [jaw_pts_0, jaw_pts_1, jaw_pts_2]:
        s_pts = ", ".join(f"{{ {tx(p['x'])}, {ty(p['y'])} }}" for p in j_pts)
        lines.append(f"    {{ {s_pts} }},")
    lines.append("};")
    lines.append("")

    # Upper Lip across 3x3 grid (12 points)
    lines.append("#define NV_NUPPER_LIP 12")
    lines.append("static const nv_pt_t NV_UPPER_LIP[3][3][NV_NUPPER_LIP] = {")
    for r in range(3):
        lines.append("    {")
        for c in range(3):
            v_name = grid_3x3[r][c]
            pts = male['vowels'][v_name]['upper_lip'][:12]
            s_pts = ", ".join(f"{{ {tx(p['x'])}, {ty(p['y'])} }}" for p in pts)
            lines.append(f"        /* ({r},{c}) */ {{ {s_pts} }},")
        lines.append("    },")
    lines.append("};")
    lines.append("")

    # Lower Lip across 3x3 grid (12 points)
    lines.append("#define NV_NLOWER_LIP 12")
    lines.append("static const nv_pt_t NV_LOWER_LIP[3][3][NV_NLOWER_LIP] = {")
    for r in range(3):
        lines.append("    {")
        for c in range(3):
            v_name = grid_3x3[r][c]
            pts = male['vowels'][v_name]['lower_lip'][:12]
            s_pts = ", ".join(f"{{ {tx(p['x'])}, {ty(p['y'])} }}" for p in pts)
            lines.append(f"        /* ({r},{c}) */ {{ {s_pts} }},")
        lines.append("    },")
    lines.append("};")
    lines.append("")

    # Velum flap (22 points, neutral schwa)
    velum_pts = male['vowels']['ə']['velum'][:22]
    lines.append(f"#define NV_NVELUM {len(velum_pts)}")
    lines.append(f"static const nv_pt_t NV_VELUM[{len(velum_pts)}] = {{")
    for p in velum_pts:
        lines.append(f"    {{ {tx(p['x'])}, {ty(p['y'])} }},")
    lines.append("};")
    lines.append("")

    # Rays (36 rungs) for neutral / schwa
    schwa_rays = male['vowels']['ə']['rays']
    lines.append(f"#define NV_NRAYS {len(schwa_rays)}")
    lines.append(f"static const nv_ray_t NV_RAYS[{len(schwa_rays)}] = {{")
    for r in schwa_rays:
        ix, iy = tx(r['inner']['x']), ty(r['inner']['y'])
        ox, oy = tx(r['outer']['x']), ty(r['outer']['y'])
        lines.append(f"    {{ {{ {ix}, {iy} }}, {{ {ox}, {oy} }} }},")
    lines.append("};")
    lines.append("")

    # 6. Hershey Simplex Vector Font Table
    # Pack strokes into a single int8_t array with (-128, -128) as PEN_UP
    all_strokes = []
    glyph_records = []
    for g in glyphs:
        offset = len(all_strokes)
        n_pts = 0
        for stroke_idx, stroke in enumerate(g['strokes']):
            if stroke_idx > 0:
                all_strokes.append((-128, -128)) # PEN UP
            for px, py in stroke:
                all_strokes.append((px, py))
                n_pts += 1
        all_strokes.append((-128, -128)) # End of glyph
        glyph_records.append({
            'ascii': g['ascii'],
            'width': g['width'],
            'offset': offset,
            'len': len(all_strokes) - offset
        })

    lines.append(f"#define NV_NFONT_PTS {len(all_strokes)}")
    lines.append(f"static const int8_t NV_FONT_DATA[{len(all_strokes)}][2] = {{")
    for x, y in all_strokes:
        lines.append(f"    {{ {x}, {y} }},")
    lines.append("};")
    lines.append("")
    lines.append(f"#define NV_NGLYPHS {len(glyph_records)}")
    lines.append("typedef struct { uint8_t width; uint16_t offset; uint8_t len; } nv_glyph_info_t;")
    lines.append(f"static const nv_glyph_info_t NV_GLYPHS[{len(glyph_records)}] = {{")
    for gr in glyph_records:
        lines.append(f"    /* {gr['ascii']} '{chr(gr['ascii']) if 32 <= gr['ascii'] <= 126 else '?'}' */ {{ {gr['width']}, {gr['offset']}, {gr['len']} }},")
    lines.append("};")
    lines.append("")
    lines.append("#endif /* NV_TABLES_H */")

    OUT_HEADER.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_HEADER, 'w') as f:
        f.write("\n".join(lines) + "\n")
    print(f"Generated {OUT_HEADER} ({len(lines)} lines, {OUT_HEADER.stat().st_size} bytes)")

if __name__ == "__main__":
    main()
